import {spawnSync} from 'node:child_process';
import {createCipheriv,createDecipheriv,randomBytes,createHash} from 'node:crypto';
import path from 'node:path';

// Platform boundary: the application and SIWC use only this encryption interface.
// Credentials never enter the portable capture library or the synchronization store.
export async function createCredentialProtection({base,vault,platform=process.platform}) {
 if(platform==='win32'){
  const crypt=(mode,bytes)=>{
   const r=spawnSync(path.join(base,'backend','SecureStore.exe'),[mode],{input:Buffer.from(bytes).toString('base64'),encoding:'utf8',windowsHide:true,maxBuffer:4*1024*1024});
   if(r.status!==0)throw new Error('Windows 凭证保护不可用；未保存明文凭证。');
   return Buffer.from(r.stdout.trim(),'base64');
  };
  return {id:'windows-dpapi-currentuser-lumashot-v1',isAvailable:()=>true,encrypt:s=>crypt('protect',Buffer.from(s)),decrypt:b=>crypt('unprotect',b).toString('utf8')};
 }
 if(platform==='darwin'){
  // macOS build installs the same package with its Darwin native binary.
  // The AES wrapping key lives only in Keychain; it is never hardcoded or saved beside the payload.
  const {Entry}=await import('@napi-rs/keyring');
  const account=createHash('sha256').update(vault).digest('hex');
  const entry=new Entry('app.lumashot.credentials.v1',account);
  let saved=entry.getPassword();
  if(saved===null||saved===undefined){saved=randomBytes(32).toString('base64');entry.setPassword(saved);}
  const key=Buffer.from(saved,'base64');if(key.length!==32)throw new Error('Keychain 凭证密钥无效；已停止读取。');
  return keychainProtection(key);
 }
 throw new Error('当前平台尚无已配置的安全凭证存储。');
}
// Exported for deterministic format/tamper tests; production keys are generated by Keychain adapter.
export function keychainProtection(key){
 return {id:'macos-keychain-aes256gcm-lumashot-v1',isAvailable:()=>true,
  encrypt(plaintext){const iv=randomBytes(12);const cipher=createCipheriv('aes-256-gcm',key,iv);cipher.setAAD(Buffer.from('lumashot.credentials.v1'));const body=Buffer.concat([cipher.update(plaintext,'utf8'),cipher.final()]);return Buffer.concat([Buffer.from([1]),iv,cipher.getAuthTag(),body]);},
  decrypt(bytes){const b=Buffer.from(bytes);if(b.length<29||b[0]!==1)throw new Error('凭证格式不受支持。');const decipher=createDecipheriv('aes-256-gcm',key,b.subarray(1,13));decipher.setAAD(Buffer.from('lumashot.credentials.v1'));decipher.setAuthTag(b.subarray(13,29));return Buffer.concat([decipher.update(b.subarray(29)),decipher.final()]).toString('utf8');}
 };
}
